const { contextBridge, ipcRenderer } = require("electron")

contextBridge.exposeInMainWorld("desk", {
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (s) => ipcRenderer.invoke("settings:set", s),
  pickFolder: (title) => ipcRenderer.invoke("dialog:folder", title),
  pickFile: (title) => ipcRenderer.invoke("dialog:file", title),
  termStart: (id, kind, args, cols, rows) => ipcRenderer.invoke("term:start", id, kind, args, cols, rows),
  termStop: (id, graceful) => ipcRenderer.invoke("term:stop", id, graceful),
  termRunning: (id) => ipcRenderer.invoke("term:running", id),
  termWrite: (id, data) => ipcRenderer.send("term:write", id, data),
  termResize: (id, cols, rows) => ipcRenderer.send("term:resize", id, cols, rows),
  onTermData: (fn) => ipcRenderer.on("term:data", (_e, id, d) => fn(id, d)),
  onTermExit: (fn) => ipcRenderer.on("term:exit", (_e, id, code) => fn(id, code)),
  strataHealth: () => ipcRenderer.invoke("strata:health"),
  strataStatus: () => ipcRenderer.invoke("strata:status"),
  strataBase: () => ipcRenderer.invoke("strata:base"),
  agentStart: () => ipcRenderer.invoke("agent:start"),
  agentStop: () => ipcRenderer.invoke("agent:stop"),
  agentRestart: () => ipcRenderer.invoke("agent:restart"),
  agentRunning: () => ipcRenderer.invoke("agent:running"),
  agentReady: () => ipcRenderer.invoke("agent:ready"),
  agentLog: () => ipcRenderer.invoke("agent:log"),
  agentCredentials: () => ipcRenderer.invoke("agent:credentials"),
  onAgentLog: (fn) => ipcRenderer.on("agent:log", (_e, s) => fn(s)),
  onAgentState: (fn) => ipcRenderer.on("agent:state", (_e, s) => fn(s)),
  openExternal: (url) => ipcRenderer.invoke("open:external", url),
  openPath: (p) => ipcRenderer.invoke("open:path", p),
  info: () => ipcRenderer.invoke("app:info"),
})
